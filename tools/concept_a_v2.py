# ---------------------------------------------------------------- small parts
def status(v):
    return v.get("displayStatus", v["status"])


def chips(v):
    s = status(v)
    cls = "live" if s == "LIVE" else "active" if s.startswith("ACTIVE") else "shipped"
    return f'<span class="ty">{E(v["displayType"])}</span><span class="st st-{cls}"><i aria-hidden="true"></i>{E(s)}</span>'


def vhref(ctx, v):
    if v["detail"]:
        return ctx.to(f'ventures/{v["id"]}/')
    if v.get("internal"):
        return ctx.to(f'{v["internal"]}/#domains')
    return ctx.to(f'ventures/#{v["id"]}')


def metas(v, keys=None, cls="meta"):
    m = dict(v["meta"])
    rows = [(k, m[k]) for k in keys] if keys else [(k, x) for k, x in v["meta"] if k != "Status"]
    return f'<dl class="{cls}">' + "".join(f"<div><dt>{E(k)}</dt><dd>{E(x)}</dd></div>" for k, x in rows) + "</dl>"


def raw(v, open_=False):
    a = v.get("artifact")
    if not a:
        return ""
    lines = "".join(f'<div class="ln"><span class="tag">{E(t)}</span><code>{E(x)}</code></div>' for t, x in a["lines"])
    fig = f'<figure class="art"><div class="art-bar"><b>{E(a["title"])}</b></div><div class="art-body">{lines}</div><figcaption>{E(a["caption"])}</figcaption></figure>'
    if open_:
        return fig
    return f'<details class="rawd"><summary><span>Raw transaction evidence</span><em>The request and reply as recorded onchain</em></summary>{fig}</details>'


def flowviz(v, labels=None, h="h3"):
    labels = labels or []
    items = ""
    for i, (t, x) in enumerate(v["flow"]):
        k = f'<span class="fx-k">{E(labels[i])}</span>' if i < len(labels) else ""
        items += f'<li class="fx-s"><span class="fx-n">{i + 1:02d}</span><{h} class="fx-v">{E(SHORT_VERB.get(t, t))}</{h}>{k}<p>{E(x)}</p></li>'
    return f'<div class="fx" data-fx style="--n:{len(v["flow"])}"><div class="fx-track" aria-hidden="true"><i class="fx-fill"></i><i class="fx-dot"></i></div><ol class="fx-l">{items}</ol></div>'


def evis(v):
    e = v.get("evidenceVisual")
    if not e:
        return ""
    if e["kind"] == "transfer":
        return f"""<div class="tv" role="img" aria-label="{E(e['a'])} sends {E(e['out'])} to the {E(e['b'].lower())}. The {E(e['b'].lower())} returns {E(e['back'])}. {E(e['note'])}.">
<span class="tv-n">{E(e['a'])}</span><span class="tv-m" aria-hidden="true"><span class="tv-o">{E(e['out'])}</span><span class="tv-b">{E(e['back'])}</span></span><span class="tv-n">{E(e['b'])}</span><span class="tv-x">{E(e['note'])}</span></div>"""
    if e["kind"] == "ratio":
        pct = round(100 * e["part"] / e["total"], 1)
        return f"""<div class="rt" role="img" aria-label="{e['part']} of {e['total']} {E(e['totalLabel'])} became {E(e['partLabel'])}.">
<div class="rt-bar" aria-hidden="true"><i style="width:{pct}%"></i></div><p aria-hidden="true"><b>{e['part']}</b> {E(e['partLabel'])}<span>of {e['total']} {E(e['totalLabel'])}</span></p></div>"""
    return ""


